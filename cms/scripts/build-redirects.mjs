// Builds cms/public/_redirects from the review site's WordPress redirects (../public/_redirects)
// and redirects/url-map.json. Page targets like /careers.html become /careers/; document and
// media targets are unchanged. Rules whose source already IS the new URL are dropped (they would loop).
// Review-site .html addresses also get redirects so shared review links keep working.
// Wildcard rules stay last: Cloudflare counts every rule after the first wildcard as dynamic (limit 100).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const map = JSON.parse(fs.readFileSync(path.join(root, 'redirects/url-map.json'), 'utf8'));
const source = fs.readFileSync(path.resolve(root, '../public/_redirects'), 'utf8');

const pageUrl = {};
for (const [file, url] of Object.entries(map.pages)) {
  pageUrl[`/${file}`] = url;
  pageUrl[`/es-${file}`] = url === '/' ? `${map.spanishPrefix}/` : `${map.spanishPrefix}${url}`;
}

const retarget = (target) => {
  const [p, hash] = target.split('#');
  if (!p.endsWith('.html')) return target;
  const url = pageUrl[p];
  if (!url) throw new Error(`No new URL for redirect target ${p}; add it to redirects/url-map.json`);
  return hash ? `${url}#${hash}` : url;
};
const norm = (u) => u.split('#')[0].replace(/\/+$/, '') || '/';

const fixed = [];
const wild = [];
const seen = new Set();
const dropped = [];
const add = (from, to, status) => {
  if (seen.has(from)) return;
  if (norm(from) === norm(to)) { dropped.push(from); return; }
  seen.add(from);
  (from.includes('*') ? wild : fixed).push(`${from} ${to} ${status}`);
};

// Paths the EmDash site now serves itself: the old WordPress feed address is the site-wide RSS feed.
// null = drop the WordPress rule; a string = new target.
const SERVED = { '/feed/': null, '/feed': '/feed/' };

for (const line of source.split(/\r?\n/)) {
  const t = line.trim();
  if (!t || t.startsWith('#')) continue;
  const [from, to, status = '301'] = t.split(/\s+/);
  if (from in SERVED) {
    if (SERVED[from]) add(from, SERVED[from], status);
    continue;
  }
  add(from, retarget(to), status);
}
// Review-site addresses (shared during design review) -> new URLs.
for (const [from, to] of Object.entries(pageUrl)) add(from, to, '301');

const out = [
  '# Generated by scripts/build-redirects.mjs. Do not edit; change redirects/url-map.json',
  '# or the WordPress rules in ../public/_redirects, then rebuild.',
  ...fixed,
  '# Wildcards last: every rule after the first wildcard counts toward the 100 dynamic-rule limit.',
  ...wild,
  '',
].join('\n');
fs.mkdirSync(path.join(root, 'public'), { recursive: true });
fs.writeFileSync(path.join(root, 'public/_redirects'), out);
if (fixed.length > 2000 || wild.length > 100) throw new Error('Cloudflare _redirects limits exceeded');
console.log(`${fixed.length} static + ${wild.length} wildcard rules; dropped ${dropped.length} that would loop: ${dropped.join(' ')}`);
